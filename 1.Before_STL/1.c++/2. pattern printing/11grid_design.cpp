void func(int i, int j, int r, int c){
    if(i%3==0 || j%3==0)cout<<"*";
    else cout<<".";
    return ;
}

int main(){
    ios_base::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);

    int t;
    cin>>t;

    while(t--){
        int n,m;
        cin>>n>>m;

        for(int i=0;i<n*2+n+1;i++){
            for(int j=0;j<m*3+1;j++){
                func(i,j,n*2+n+1,m*3+1);
            }
            cout<<"\n";
        }
    }
    
    return 0;
}
